use std::{
    ffi::OsString,
    fs::{self, File},
    io,
    os::unix::fs::{MetadataExt, PermissionsExt},
    path::Path,
};

#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct Policy {
    uid: u32,
    gid: u32,
    mode: u32,
    attributes: Vec<(OsString, Vec<u8>)>,
    #[cfg(any(target_os = "macos", target_os = "freebsd"))]
    acl: Vec<exacl::AclEntry>,
}

impl Policy {
    pub fn read(path: &Path) -> io::Result<Self> {
        let metadata = fs::metadata(path)?;
        let mut attributes = Vec::new();
        for name in xattr::list(path)? {
            let text = name.to_string_lossy();
            if text.starts_with("security.") || text.starts_with("system.") {
                let value = xattr::get(path, &name)?.ok_or_else(|| io::Error::other("access attribute changed while reading"))?;
                if value.len() > 1_048_576 || attributes.len() >= 128 {
                    return Err(io::Error::other("export access metadata exceeds supported limits"));
                }
                attributes.push((name, value));
            }
        }
        attributes.sort_by(|a, b| a.0.cmp(&b.0));
        Ok(Self {
            uid: metadata.uid(),
            gid: metadata.gid(),
            mode: metadata.mode() & 0o7777,
            attributes,
            #[cfg(any(target_os = "macos", target_os = "freebsd"))]
            acl: exacl::getfacl(path, None)?,
        })
    }

    pub fn apply(&self, path: &Path) -> io::Result<()> {
        // An export is data, not a privileged executable. Do not transfer privilege bits or
        // file capabilities onto newly generated bytes.
        if self.mode & 0o7000 != 0 || self.attributes.iter().any(|(name, _)| name == "security.capability") {
            return Err(io::Error::other("cannot replace an export destination carrying executable privileges"));
        }
        let current = fs::metadata(path)?;
        // Do not grant the destination owner the staging inode's initial owner-read bit
        // while transferring ownership. ACL grants/denials are installed before final mode.
        fs::set_permissions(path, fs::Permissions::from_mode(0))?;
        if (current.uid(), current.gid()) != (self.uid, self.gid) {
            std::os::unix::fs::chown(path, Some(self.uid), Some(self.gid))?;
        }
        for (name, _) in Self::read(path)?.attributes {
            if !self.attributes.iter().any(|(wanted, _)| wanted == &name) {
                xattr::remove(path, name)?;
            }
        }
        for (name, value) in &self.attributes {
            if xattr::get(path, name)?.as_deref() != Some(value.as_slice()) {
                xattr::set(path, name, value)?;
            }
        }
        #[cfg(any(target_os = "macos", target_os = "freebsd"))]
        exacl::setfacl(&[path], &self.acl, None)?;
        // Restore access ACLs before mode bits: chmod must not open an inherited ACL mask
        // or permit access before a macOS deny entry has been installed.
        fs::set_permissions(path, fs::Permissions::from_mode(self.mode))?;
        Ok(())
    }
}

pub(super) fn ordinary_file(parent: &Path) -> io::Result<tempfile::NamedTempFile> {
    tempfile::Builder::new().prefix(".effectcraft-policy-").permissions(fs::Permissions::from_mode(0o666)).tempfile_in(parent)
}

pub(super) fn private_file(parent: &Path) -> io::Result<(tempfile::NamedTempFile, Option<tempfile::TempDir>)> {
    #[cfg(any(target_os = "macos", target_os = "freebsd"))]
    {
        // macOS ACL allows can override mode 0600. Clear inheritance in an empty owned
        // directory before creating the media inode; the empty directory never holds media.
        let directory = tempfile::Builder::new().prefix(".effectcraft-export-").tempdir_in(parent)?;
        #[cfg(target_os = "macos")]
        exacl::setfacl(&[directory.path()], &[], None)?;
        #[cfg(target_os = "freebsd")]
        exacl::setfacl(
            &[directory.path()],
            &[
                exacl::AclEntry::allow_user("", exacl::Perm::READ | exacl::Perm::WRITE | exacl::Perm::EXECUTE, None),
                exacl::AclEntry::allow_group("", exacl::Perm::empty(), None),
                exacl::AclEntry::allow_other(exacl::Perm::empty(), None),
            ],
            None,
        )?;
        fs::set_permissions(directory.path(), fs::Permissions::from_mode(0o700))?;
        let file = tempfile::NamedTempFile::new_in(directory.path())?;
        Ok((file, Some(directory)))
    }
    #[cfg(not(any(target_os = "macos", target_os = "freebsd")))]
    Ok((tempfile::Builder::new().prefix(".effectcraft-export-").tempfile_in(parent)?, None))
}

pub(super) fn identity(file: &File) -> io::Result<(u64, u64)> {
    let metadata = file.metadata()?;
    Ok((metadata.dev(), metadata.ino()))
}

pub(super) fn links(file: &File) -> io::Result<u64> {
    Ok(file.metadata()?.nlink())
}

pub(super) fn change_stamp(file: &File) -> io::Result<(i64, i64)> {
    let metadata = file.metadata()?;
    Ok((metadata.ctime(), metadata.ctime_nsec()))
}
